#include "minishell.h"

int	ft_is_delimiter(char c)
{
	if (c == '<')
	{
		return (1);
	}
	else if (c == '>')
	{
		return (1);
	}
	else if (c == '|')
	{
		return (1);
	}
	return (0);
}
